CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    category VARCHAR(20) NOT NULL CHECK (category IN ('FUEL','SERVICE','INSURANCE','TAXES','PARKING','WASH','OTHER')),
    amount_pln NUMERIC(12,2) NOT NULL CHECK (amount_pln > 0),
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    description VARCHAR(2000),
    source_type VARCHAR(20) NOT NULL CHECK (source_type IN ('MANUAL','FUEL','SERVICE')),
    source_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    UNIQUE(source_type, source_id),
    CHECK ((source_type = 'FUEL' AND category = 'FUEL') OR (source_type = 'SERVICE' AND category = 'SERVICE') OR (source_type = 'MANUAL' AND category <> 'FUEL'))
);
CREATE INDEX idx_expenses_vehicle_date ON expenses(vehicle_id, date DESC, id);
CREATE TABLE refuelings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    odometer_km INTEGER NOT NULL CHECK (odometer_km >= 0),
    liters NUMERIC(10,3) NOT NULL CHECK (liters > 0),
    is_full_tank BOOLEAN NOT NULL,
    station VARCHAR(120),
    note VARCHAR(1000),
    expense_id BIGINT NOT NULL UNIQUE REFERENCES expenses(id) DEFERRABLE INITIALLY DEFERRED,
    odometer_entry_id BIGINT NOT NULL UNIQUE REFERENCES odometer_entries(id) DEFERRABLE INITIALLY DEFERRED,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_refuelings_vehicle_date ON refuelings(vehicle_id, date DESC, id);
CREATE TABLE service_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    service_type VARCHAR(30) NOT NULL CHECK (service_type IN ('REPAIR','OIL_CHANGE','TIRES','BRAKES','INSPECTION','OTHER')),
    odometer_km INTEGER CHECK (odometer_km >= 0),
    description VARCHAR(2000) NOT NULL CHECK (length(trim(description)) > 0),
    workshop VARCHAR(120),
    next_due_date DATE,
    next_due_odometer_km INTEGER CHECK (next_due_odometer_km >= 0),
    expense_id BIGINT UNIQUE REFERENCES expenses(id) DEFERRABLE INITIALLY DEFERRED,
    odometer_entry_id BIGINT UNIQUE REFERENCES odometer_entries(id) DEFERRABLE INITIALLY DEFERRED,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CHECK (next_due_date IS NULL OR next_due_date >= date),
    CHECK (next_due_odometer_km IS NULL OR odometer_km IS NULL OR next_due_odometer_km >= odometer_km)
);
CREATE INDEX idx_service_vehicle_date ON service_records(vehicle_id, date DESC, id);
CREATE TABLE document_deadlines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
    type VARCHAR(20) NOT NULL CHECK (type IN ('INSURANCE','INSPECTION')),
    valid_until DATE NOT NULL,
    note VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_documents_vehicle_date ON document_deadlines(vehicle_id, valid_until DESC, id);
CREATE TABLE journal_commands (
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
    resource VARCHAR(20) NOT NULL,
    request_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    result_id BIGINT NOT NULL,
    PRIMARY KEY(vehicle_id, resource, request_key)
);
