CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT users_email_normalized CHECK (email = lower(trim(email)))
);
CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    make VARCHAR(80) NOT NULL CHECK (length(trim(make)) > 0),
    model VARCHAR(80) NOT NULL CHECK (length(trim(model)) > 0),
    year INTEGER NOT NULL CHECK (year BETWEEN 1886 AND 2100),
    generation VARCHAR(80),
    fuel_type VARCHAR(20) NOT NULL CHECK (fuel_type IN ('PETROL','DIESEL','LPG','HYBRID','ELECTRIC','OTHER')),
    engine_capacity_liters NUMERIC(4,2) CHECK (engine_capacity_liters > 0 AND engine_capacity_liters <= 20),
    vin VARCHAR(17) CHECK (vin ~ '^[A-HJ-NPR-Z0-9]{17}$'),
    registration_number VARCHAR(20),
    purchase_date DATE,
    current_odometer_km INTEGER NOT NULL CHECK (current_odometer_km >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_vehicles_user_created ON vehicles(user_id, created_at DESC, id);
